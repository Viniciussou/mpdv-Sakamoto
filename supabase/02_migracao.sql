create or replace function public.mpdv_registrar_movimento() returns trigger
language plpgsql security definer set search_path = '' as $$
declare v_delta integer; v_tipo text;
begin
  if tg_op = 'INSERT' then
    v_delta := coalesce(new.estoque, 0); v_tipo := 'cadastro';
  else
    v_delta := coalesce(new.estoque, 0) - coalesce(old.estoque, 0);
    v_tipo  := coalesce(nullif(current_setting('app.mov_tipo', true), ''), 'ajuste');
  end if;
  if v_delta = 0 then return new; end if;

  insert into public.estoque_movimentos_mpdv (material_id, delta, saldo_apos, tipo, solicitacao_id, motivo, usuario_id)
  values (new.id, v_delta, new.estoque, v_tipo,
          nullif(current_setting('app.mov_solicitacao', true), '')::uuid,
          nullif(current_setting('app.mov_motivo', true), ''),
          auth.uid());
  return new;
end $$;

drop trigger if exists mpdv_material_movimento_ins on public.materiais_mpdv;
create trigger mpdv_material_movimento_ins after insert on public.materiais_mpdv
  for each row execute function public.mpdv_registrar_movimento();
drop trigger if exists mpdv_material_movimento_upd on public.materiais_mpdv;
create trigger mpdv_material_movimento_upd after update of estoque on public.materiais_mpdv
  for each row execute function public.mpdv_registrar_movimento();

create or replace function public.mpdv_auditar() returns trigger
language plpgsql security definer set search_path = '' as $$
declare v_old jsonb; v_new jsonb;
begin
  if tg_op = 'INSERT' then
    insert into public.auditoria_mpdv (tabela, registro_id, acao, usuario_id, depois)
    values (tg_table_name, (to_jsonb(new)->>'id'), 'INSERT', auth.uid(), to_jsonb(new));
  elsif tg_op = 'UPDATE' then
    v_old := to_jsonb(old) - 'atualizado_em' - 'estoque';
    v_new := to_jsonb(new) - 'atualizado_em' - 'estoque';
    if v_old is distinct from v_new then
      insert into public.auditoria_mpdv (tabela, registro_id, acao, usuario_id, antes, depois)
      values (tg_table_name, (to_jsonb(new)->>'id'), 'UPDATE', auth.uid(), to_jsonb(old), to_jsonb(new));
    end if;
  else
    insert into public.auditoria_mpdv (tabela, registro_id, acao, usuario_id, antes)
    values (tg_table_name, (to_jsonb(old)->>'id'), 'DELETE', auth.uid(), to_jsonb(old));
  end if;
  return null;
end $$;

drop trigger if exists mpdv_audit_materiais on public.materiais_mpdv;
create trigger mpdv_audit_materiais after insert or update or delete on public.materiais_mpdv
  for each row execute function public.mpdv_auditar();
drop trigger if exists mpdv_audit_perfis on public.perfis_mpdv;
create trigger mpdv_audit_perfis after insert or update or delete on public.perfis_mpdv
  for each row execute function public.mpdv_auditar();

-- 6.4 Histórico é imutável (append-only)
-- (exclusões em CASCATA — nível de trigger > 1 — continuam permitidas; DELETE/UPDATE diretos não)
create or replace function public.mpdv_imutavel() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'DELETE' and pg_trigger_depth() > 1 then return old; end if;
  raise exception 'Registros de histórico não podem ser alterados ou apagados.';
end $$;

drop trigger if exists mpdv_hist_imutavel on public.solicitacao_historico_mpdv;
create trigger mpdv_hist_imutavel before update or delete on public.solicitacao_historico_mpdv
  for each row execute function public.mpdv_imutavel();
drop trigger if exists mpdv_mov_imutavel on public.estoque_movimentos_mpdv;
create trigger mpdv_mov_imutavel before update or delete on public.estoque_movimentos_mpdv
  for each row execute function public.mpdv_imutavel();

