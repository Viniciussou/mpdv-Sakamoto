-- 9.4 Estoque (atômico, com trava e registro de movimento)
create or replace function public.mpdv_ajustar_estoque(p_material_id text, p_delta integer, p_motivo text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_m record;
begin
  perform public.mpdv_exigir_marketing();
  if p_delta is null or p_delta = 0 then
    raise exception 'Informe uma quantidade diferente de zero.' using errcode = 'P0001', detail = 'ITENS_INVALIDOS';
  end if;
  select m.id, m.estoque into v_m from public.materiais_mpdv m where m.id::text = p_material_id for update;
  if not found then
    raise exception 'Produto não encontrado.' using errcode = 'P0001', detail = 'NAO_ENCONTRADA';
  end if;
  if coalesce(v_m.estoque, 0) + p_delta < 0 then
    raise exception 'O estoque não pode ficar negativo (atual: %).', coalesce(v_m.estoque, 0) using errcode = 'P0001', detail = 'ESTOQUE_INSUFICIENTE';
  end if;
  perform set_config('app.mov_tipo', 'ajuste', true);
  perform set_config('app.mov_motivo', left(coalesce(p_motivo, ''), 300), true);
  update public.materiais_mpdv set estoque = coalesce(estoque, 0) + p_delta where id = v_m.id;
  perform set_config('app.mov_tipo', '', true);
  perform set_config('app.mov_motivo', '', true);
  return jsonb_build_object('estoque', coalesce(v_m.estoque, 0) + p_delta);
end $$;

create or replace function public.mpdv_definir_estoque(p_material_id text, p_novo integer, p_motivo text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_atual integer;
begin
  perform public.mpdv_exigir_marketing();
  if p_novo is null or p_novo < 0 then
    raise exception 'O estoque deve ser zero ou maior.' using errcode = 'P0001', detail = 'ITENS_INVALIDOS';
  end if;
  select coalesce(m.estoque, 0) into v_atual from public.materiais_mpdv m where m.id::text = p_material_id for update;
  if not found then
    raise exception 'Produto não encontrado.' using errcode = 'P0001', detail = 'NAO_ENCONTRADA';
  end if;
  if p_novo = v_atual then
    return jsonb_build_object('estoque', v_atual);
  end if;
  return public.mpdv_ajustar_estoque(p_material_id, p_novo - v_atual, p_motivo);
end $$;

-- 9.5 Painel
create or replace function public.mpdv_dashboard(p_mes date default null)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare v_mes date := case when p_mes is null then null else date_trunc('month', p_mes)::date end;
        v_res jsonb;
begin
  perform public.mpdv_exigir_marketing();
  select jsonb_build_object(
    'total',              count(*),
    'aguardando_analise', count(*) filter (where status = 'aguardando_analise'),
    'aprovado',           count(*) filter (where status = 'aprovado'),
    'em_separacao',       count(*) filter (where status = 'em_separacao'),
    'em_transporte',      count(*) filter (where status = 'em_transporte'),
    'entregue',           count(*) filter (where status = 'entregue'),
    'cancelado',          count(*) filter (where status = 'cancelado'),
    'rejeitado',          count(*) filter (where status = 'rejeitado')
  ) into v_res
  from public.solicitacoes_mpdv where v_mes is null or mes_referencia = v_mes;

  return v_res || jsonb_build_object(
    'vendedores_total', (select count(*) from public.perfis_mpdv where papel = 'vendedor'),
    'vendedores_ativos', (select count(*) from public.perfis_mpdv where papel = 'vendedor' and ativo),
    'estoque_baixo', (select count(*) from public.materiais_mpdv where ativo and coalesce(estoque, 0) <= estoque_minimo),
    'estoque_baixo_itens', coalesce((
        select jsonb_agg(x) from (
          select jsonb_build_object('id', id, 'nome', nome, 'estoque', coalesce(estoque, 0), 'minimo', estoque_minimo) as x
          from public.materiais_mpdv where ativo and coalesce(estoque, 0) <= estoque_minimo
          order by coalesce(estoque, 0), nome limit 8) t), '[]'::jsonb)
  );
end $$;

-- 9.6 Vendedores
create or replace function public.mpdv_listar_vendedores()
returns table (id uuid, nome text, email text, ativo boolean, criado_em timestamptz,
               total_solicitacoes bigint, ultima_solicitacao timestamptz, status_mes text)
language plpgsql stable security definer set search_path = '' as $$
begin
  perform public.mpdv_exigir_marketing();
  return query
    select p.id, p.nome, p.email, p.ativo, p.criado_em,
           (select count(*) from public.solicitacoes_mpdv s where s.vendedor_id = p.id),
           (select max(s.criado_em) from public.solicitacoes_mpdv s where s.vendedor_id = p.id),
           (select s.status from public.solicitacoes_mpdv s
             where s.vendedor_id = p.id and s.mes_referencia = public.mpdv_mes_atual()
               and s.status not in ('cancelado','rejeitado') limit 1)
    from public.perfis_mpdv p where p.papel = 'vendedor' order by p.nome nulls last, p.email;
end $$;

create or replace function public.mpdv_atualizar_vendedor(p_id uuid, p_nome text default null, p_ativo boolean default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_p public.perfis_mpdv;
begin
  perform public.mpdv_exigir_marketing();
  select * into v_p from public.perfis_mpdv where id = p_id and papel = 'vendedor' for update;
  if not found then
    raise exception 'Vendedor não encontrado.' using errcode = 'P0001', detail = 'NAO_ENCONTRADA';
  end if;
  update public.perfis_mpdv
     set nome = coalesce(left(nullif(trim(p_nome), ''), 120), nome),
         ativo = coalesce(p_ativo, ativo)
   where id = p_id;
  return jsonb_build_object('id', p_id, 'ativo', coalesce(p_ativo, v_p.ativo));
end $$;

