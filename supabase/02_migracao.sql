create or replace function public.mpdv_devolver_estoque(p_solicitacao uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare r record;
begin
  perform set_config('app.mov_tipo', 'devolucao', true);
  perform set_config('app.mov_solicitacao', p_solicitacao::text, true);
  for r in select i.material_id, i.quantidade
           from public.solicitacao_itens_mpdv i
           where i.solicitacao_id = p_solicitacao
           order by i.material_id loop
    update public.materiais_mpdv set estoque = coalesce(estoque, 0) + r.quantidade where id = r.material_id;
  end loop;
  perform set_config('app.mov_tipo', '', true);
  perform set_config('app.mov_solicitacao', '', true);
end $$;

