  ativo         boolean not null default true,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 3. Solicitações
-- ---------------------------------------------------------------------
create table if not exists public.solicitacoes_mpdv (
  id                    uuid primary key default gen_random_uuid(),
  numero                bigint generated always as identity,
  vendedor_id           uuid not null references public.perfis_mpdv(id),
  mes_referencia        date not null,
  status                text not null default 'aguardando_analise'
                        check (status in ('aguardando_analise','aprovado','em_separacao','em_transporte','entregue','cancelado','rejeitado')),
  observacao_vendedor   text check (char_length(observacao_vendedor) <= 500),
  cancelamento_liberado boolean not null default false,
  cancelado_em          timestamptz,
  cancelado_por         uuid references public.perfis_mpdv(id),
  cancelado_por_papel   text check (cancelado_por_papel in ('marketing','vendedor')),
  motivo_cancelamento   text check (char_length(motivo_cancelamento) <= 500),
  criado_em             timestamptz not null default now(),
  atualizado_em         timestamptz not null default now(),
  constraint mpdv_mes_primeiro_dia check (mes_referencia = date_trunc('month', mes_referencia)::date)
);

-- *** REGRA DE NEGÓCIO NO BANCO ***
-- Uma solicitação "viva" por vendedor por mês. Cancelada/rejeitada libera nova.
-- Índice único parcial = garantia atômica mesmo contra requisições simultâneas.
create unique index if not exists mpdv_uma_solicitacao_por_mes
  on public.solicitacoes_mpdv (vendedor_id, mes_referencia)
  where status not in ('cancelado','rejeitado');

create index if not exists mpdv_sol_vendedor_idx on public.solicitacoes_mpdv (vendedor_id, criado_em desc);
create index if not exists mpdv_sol_status_idx   on public.solicitacoes_mpdv (status, criado_em desc);

-- ---------------------------------------------------------------------
-- 4. Itens, histórico, notas internas, movimentos de estoque
--    (material_id acompanha o tipo real de materiais_mpdv.id)
-- ---------------------------------------------------------------------
do $$
declare v_tipo text;
begin
  select format_type(a.atttypid, a.atttypmod) into v_tipo
  from pg_attribute a
  where a.attrelid = 'public.materiais_mpdv'::regclass and a.attname = 'id' and not a.attisdropped;

  execute format($f$
    create table if not exists public.solicitacao_itens_mpdv (
      id               uuid primary key default gen_random_uuid(),
      solicitacao_id   uuid not null references public.solicitacoes_mpdv(id) on delete cascade,
      material_id      %1$s not null references public.materiais_mpdv(id) on delete restrict,
      nome_snapshot    text not null,
      categoria_snapshot text,
      quantidade       integer not null check (quantidade > 0),
      unique (solicitacao_id, material_id)
    )$f$, v_tipo);

  execute format($f$
    create table if not exists public.estoque_movimentos_mpdv (
      id             bigint generated always as identity primary key,
      material_id    %1$s not null references public.materiais_mpdv(id) on delete cascade,
      delta          integer not null,
      saldo_apos     integer,
      tipo           text not null,
      solicitacao_id uuid,
      motivo         text,
      usuario_id     uuid,
      criado_em      timestamptz not null default now()
    )$f$, v_tipo);
end $$;

create index if not exists mpdv_itens_sol_idx on public.solicitacao_itens_mpdv (solicitacao_id);
create index if not exists mpdv_mov_mat_idx   on public.estoque_movimentos_mpdv (material_id, criado_em desc);

