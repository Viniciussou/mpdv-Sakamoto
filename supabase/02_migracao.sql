-- 8.1 Estado do mês (autoridade do servidor para avisos/bloqueios na interface)
create or replace function public.mpdv_estado_mes() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_sol record; v_mes date := public.mpdv_mes_atual();
begin
  if auth.uid() is null then
    raise exception 'Sessão expirada. Entre novamente.' using errcode = '28000', detail = 'NAO_AUTENTICADO';
  end if;
  select s.id, s.numero, s.status, s.cancelamento_liberado into v_sol
  from public.solicitacoes_mpdv s
  where s.vendedor_id = auth.uid() and s.mes_referencia = v_mes
    and s.status not in ('cancelado','rejeitado')
  limit 1;
  return jsonb_build_object(
    'mes_referencia', v_mes,
    'solicitacao', case when v_sol.id is null then null else
      jsonb_build_object('id', v_sol.id, 'numero', v_sol.numero, 'status', v_sol.status,
                         'cancelamento_liberado', v_sol.cancelamento_liberado) end);
end $$;

-- 8.2 Criar solicitação — TUDO em uma transação, com travas
create or replace function public.mpdv_criar_solicitacao(p_itens jsonb, p_observacao text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_mes date := public.mpdv_mes_atual();
  v_id uuid; v_numero bigint;
  v_ids text[]; v_item record;
  v_obs text := left(nullif(trim(coalesce(p_observacao, '')), ''), 500);
begin
  if v_uid is null then
    raise exception 'Sessão expirada. Entre novamente.' using errcode = '28000', detail = 'NAO_AUTENTICADO';
  end if;
  if public.mpdv_papel_atual() is distinct from 'vendedor' then
    raise exception 'Apenas vendedores ativos podem enviar solicitações.' using errcode = '42501', detail = 'SEM_PERMISSAO';
  end if;
  if jsonb_typeof(p_itens) is distinct from 'array' or jsonb_array_length(p_itens) = 0 then
    raise exception 'Adicione ao menos um produto ao carrinho.' using errcode = 'P0001', detail = 'CARRINHO_VAZIO';
  end if;
  if jsonb_array_length(p_itens) > 200 then
    raise exception 'Itens demais na solicitação.' using errcode = 'P0001', detail = 'ITENS_INVALIDOS';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_itens) e
    where jsonb_typeof(e) <> 'object'
       or coalesce(e->>'material_id', '') = ''
       or case when coalesce(e->>'quantidade', '') ~ '^[0-9]{1,6}$' then (e->>'quantidade')::int else 0 end < 1
  ) then
    raise exception 'Itens inválidos: informe produto e quantidade inteira maior que zero.' using errcode = 'P0001', detail = 'ITENS_INVALIDOS';
  end if;

  -- Serializa as solicitações DO MESMO vendedor (requisições simultâneas ficam em fila)
  perform pg_advisory_xact_lock(hashtextextended('mpdv:sol:' || v_uid::text, 0));

  if exists (select 1 from public.solicitacoes_mpdv s
             where s.vendedor_id = v_uid and s.mes_referencia = v_mes
               and s.status not in ('cancelado','rejeitado')) then
    raise exception 'Você já possui uma solicitação registrada neste mês. Para realizar uma nova solicitação, será necessário cancelar o pedido atual, caso ele ainda permita cancelamento.'
      using errcode = 'P0001', detail = 'LIMITE_MENSAL';
  end if;

  -- Trava os produtos em ordem fixa de ID (evita deadlock entre vendedores diferentes)
  select array_agg(distinct e->>'material_id') into v_ids from jsonb_array_elements(p_itens) e;
  perform 1 from public.materiais_mpdv m where m.id::text = any(v_ids) order by m.id for update;

  -- Valida existência, ativo e estoque (somando linhas repetidas do mesmo produto)
  for v_item in
    select a.mid, a.qtd, m.id as m_id, m.nome, m.ativo, m.estoque
    from (select e->>'material_id' as mid, sum((e->>'quantidade')::int) as qtd
          from jsonb_array_elements(p_itens) e group by 1) a
    left join public.materiais_mpdv m on m.id::text = a.mid
    order by m.id
  loop
    if v_item.m_id is null or not coalesce(v_item.ativo, false) then
      raise exception 'Um dos produtos não está mais disponível. Atualize o catálogo.' using errcode = 'P0001', detail = 'PRODUTO_INDISPONIVEL';
    end if;
    if coalesce(v_item.estoque, 0) < v_item.qtd then
      raise exception 'Estoque insuficiente para "%". Disponível: % un.', v_item.nome, coalesce(v_item.estoque, 0)
        using errcode = 'P0001', detail = 'ESTOQUE_INSUFICIENTE';
    end if;
  end loop;

  begin
    insert into public.solicitacoes_mpdv (vendedor_id, mes_referencia, observacao_vendedor)
    values (v_uid, v_mes, v_obs) returning id, numero into v_id, v_numero;
  exception when unique_violation then
    raise exception 'Você já possui uma solicitação registrada neste mês. Para realizar uma nova solicitação, será necessário cancelar o pedido atual, caso ele ainda permita cancelamento.'
      using errcode = 'P0001', detail = 'LIMITE_MENSAL';
  end;

  perform set_config('app.mov_tipo', 'reserva', true);
  perform set_config('app.mov_solicitacao', v_id::text, true);

  for v_item in
    select a.qtd, m.id as m_id, m.nome, m.categoria
    from (select e->>'material_id' as mid, sum((e->>'quantidade')::int) as qtd
          from jsonb_array_elements(p_itens) e group by 1) a
    join public.materiais_mpdv m on m.id::text = a.mid
    order by m.id
  loop
    insert into public.solicitacao_itens_mpdv (solicitacao_id, material_id, nome_snapshot, categoria_snapshot, quantidade)
    values (v_id, v_item.m_id, v_item.nome, v_item.categoria, v_item.qtd);
    update public.materiais_mpdv set estoque = estoque - v_item.qtd where id = v_item.m_id;
  end loop;

  perform set_config('app.mov_tipo', '', true);
  perform set_config('app.mov_solicitacao', '', true);

  insert into public.solicitacao_historico_mpdv (solicitacao_id, evento, status_anterior, status_novo, mensagem, usuario_id, usuario_papel)
  values (v_id, 'criacao', null, 'aguardando_analise', 'Solicitação enviada.', v_uid, 'vendedor');

  return jsonb_build_object('id', v_id, 'numero', v_numero, 'mes_referencia', v_mes);
end $$;

-- 8.3 Cancelar a PRÓPRIA solicitação
create or replace function public.mpdv_cancelar_solicitacao(p_id uuid, p_motivo text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_sol public.solicitacoes_mpdv;
  v_motivo text := left(nullif(trim(coalesce(p_motivo, '')), ''), 500);
begin
  if v_uid is null then
    raise exception 'Sessão expirada. Entre novamente.' using errcode = '28000', detail = 'NAO_AUTENTICADO';
  end if;
  if public.mpdv_papel_atual() is distinct from 'vendedor' then
    raise exception 'Apenas vendedores ativos podem cancelar solicitações.' using errcode = '42501', detail = 'SEM_PERMISSAO';
  end if;

  select * into v_sol from public.solicitacoes_mpdv where id = p_id and vendedor_id = v_uid for update;
  if not found then
    raise exception 'Solicitação não encontrada.' using errcode = 'P0001', detail = 'NAO_ENCONTRADA';
  end if;

  if v_sol.status in ('cancelado','rejeitado') then
    raise exception 'Esta solicitação já foi encerrada.' using errcode = 'P0001', detail = 'JA_ENCERRADA';
  elsif v_sol.status = 'entregue' then
    raise exception 'Esta solicitação já foi entregue e não pode ser cancelada.' using errcode = 'P0001', detail = 'CANCELAMENTO_BLOQUEADO';
  elsif v_sol.status = 'em_transporte' then
    raise exception 'Seu pedido já está em processo de entrega e não pode mais ser cancelado. Acompanhe o andamento diretamente por aqui.'
      using errcode = 'P0001', detail = 'CANCELAMENTO_BLOQUEADO';
  elsif v_sol.status = 'em_separacao' and not v_sol.cancelamento_liberado then
    raise exception 'Seu pedido está em separação. O cancelamento depende de autorização do Marketing.'
      using errcode = 'P0001', detail = 'CANCELAMENTO_BLOQUEADO';
  end if;

  perform public.mpdv_devolver_estoque(v_sol.id);

  update public.solicitacoes_mpdv
     set status = 'cancelado', cancelado_em = now(), cancelado_por = v_uid, cancelado_por_papel = 'vendedor',
         motivo_cancelamento = v_motivo, cancelamento_liberado = false, atualizado_em = now()
   where id = v_sol.id;

  insert into public.solicitacao_historico_mpdv (solicitacao_id, evento, status_anterior, status_novo, mensagem, usuario_id, usuario_papel)
  values (v_sol.id, 'cancelamento', v_sol.status, 'cancelado', coalesce(v_motivo, 'Cancelada pelo vendedor.'), v_uid, 'vendedor');

  return jsonb_build_object('id', v_sol.id, 'status', 'cancelado');
end $$;

