-- 6.1 Novo usuário no Auth => perfil SEMPRE como vendedor (marketing só via SQL)
create or replace function public.mpdv_novo_usuario() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.perfis_mpdv (id, nome, email, papel, ativo)
  values (new.id,
          left(coalesce(nullif(trim(new.raw_user_meta_data->>'nome'), ''), split_part(coalesce(new.email,''), '@', 1)), 120),
          new.email, 'vendedor', true)
  on conflict (id) do nothing;
  return new;
end $$;

create or replace function public.mpdv_sync_email() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update public.perfis_mpdv set email = new.email where id = new.id and email is distinct from new.email;
  return new;
end $$;

drop trigger if exists mpdv_on_auth_user_created on auth.users;
create trigger mpdv_on_auth_user_created after insert on auth.users
  for each row execute function public.mpdv_novo_usuario();

drop trigger if exists mpdv_on_auth_user_email on auth.users;
create trigger mpdv_on_auth_user_email after update of email on auth.users
  for each row execute function public.mpdv_sync_email();

-- Usuários que já existem viram vendedores
insert into public.perfis_mpdv (id, nome, email, papel, ativo)
select u.id, left(coalesce(nullif(trim(u.raw_user_meta_data->>'nome'), ''), split_part(coalesce(u.email,''), '@', 1)), 120), u.email, 'vendedor', true
from auth.users u
on conflict (id) do nothing;

-- 6.2 Ninguém muda o próprio papel/ID pela API (somente via SQL Editor, onde auth.uid() é nulo)
create or replace function public.mpdv_proteger_perfil() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is not null and (new.papel is distinct from old.papel or new.id is distinct from old.id) then
    raise exception 'Alteração de papel não é permitida por esta via.' using errcode = '42501', detail = 'SEM_PERMISSAO';
  end if;
  new.atualizado_em := now();
  return new;
end $$;

drop trigger if exists mpdv_perfil_protegido on public.perfis_mpdv;
create trigger mpdv_perfil_protegido before update on public.perfis_mpdv
  for each row execute function public.mpdv_proteger_perfil();

