create or replace function public.mpdv_papel_atual() returns text
language sql stable security definer set search_path = '' as $$
  select p.papel from public.perfis_mpdv p where p.id = auth.uid() and p.ativo
$$;

create or replace function public.mpdv_is_marketing() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(public.mpdv_papel_atual() = 'marketing', false)
$$;

-- Mês de referência calculado SEMPRE no servidor (fuso de Brasília).
create or replace function public.mpdv_mes_atual() returns date
language sql stable set search_path = '' as $$
  select date_trunc('month', timezone('America/Sao_Paulo', now()))::date
$$;

create or replace function public.mpdv_transicao_permitida(p_de text, p_para text) returns boolean
language sql immutable set search_path = '' as $$
  select case p_de
    when 'aguardando_analise' then p_para in ('aprovado','rejeitado','cancelado')
    when 'aprovado'           then p_para in ('aguardando_analise','em_separacao','cancelado')
    when 'em_separacao'       then p_para in ('aprovado','em_transporte','cancelado')
    when 'em_transporte'      then p_para in ('em_separacao','entregue','cancelado')
    else false end
$$;

