-- ---------------------------------------------------------------------
-- 0. Proteção: não sobrescrever tabelas de mesmo nome que não sejam nossas
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array[
    'perfis_mpdv','solicitacoes_mpdv','solicitacao_itens_mpdv',
    'solicitacao_historico_mpdv','solicitacao_notas_mpdv',
    'estoque_movimentos_mpdv','auditoria_mpdv'] loop
    if to_regclass('public.'||t) is not null
       and coalesce(obj_description(to_regclass('public.'||t), 'pg_class'), '') <> 'mpdv:v2' then
      raise exception 'A tabela public.% já existe e não foi criada por esta migração. Abortando para não sobrescrever dados.', t;
    end if;
  end loop;
end $$;

-- ---------------------------------------------------------------------
-- 1. Catálogo: materiais_mpdv (preserva a existente; cria só se faltar)
-- ---------------------------------------------------------------------
do $$
begin
  if to_regclass('public.materiais_mpdv') is null then
    create table public.materiais_mpdv (
      id        bigint generated by default as identity primary key,
      nome      text not null,
      categoria text,
      estoque   integer not null default 0,
      ativo     boolean not null default true
    );
    raise notice 'materiais_mpdv não existia e foi criada.';
  end if;
end $$;

alter table public.materiais_mpdv
  add column if not exists descricao      text,
  add column if not exists imagem_url     text,
  add column if not exists estoque_minimo integer not null default 5,
  add column if not exists criado_em      timestamptz not null default now(),
  add column if not exists atualizado_em  timestamptz not null default now();

alter table public.materiais_mpdv alter column ativo   set default true;
alter table public.materiais_mpdv alter column estoque set default 0;

-- Garante chave primária e valor padrão para "id" (necessário p/ FKs e inserts)
do $$
declare r record; v_max bigint;
begin
  if not exists (select 1 from pg_index where indrelid = 'public.materiais_mpdv'::regclass and indisprimary) then
    alter table public.materiais_mpdv add primary key (id);
  end if;

  select data_type, column_default, is_identity into r
  from information_schema.columns
  where table_schema='public' and table_name='materiais_mpdv' and column_name='id';

  if r.column_default is null and r.is_identity = 'NO' then
    if r.data_type = 'uuid' then
      alter table public.materiais_mpdv alter column id set default gen_random_uuid();
    elsif r.data_type in ('bigint','integer','smallint') then
      execute 'select coalesce(max(id),0)+1 from public.materiais_mpdv' into v_max;
      execute format('alter table public.materiais_mpdv alter column id add generated by default as identity (start with %s)', v_max);
    end if;
  end if;
end $$;

-- Estoque nunca negativo (NOT VALID: não falha por dados antigos, mas vale p/ novas gravações)
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'mpdv_estoque_nao_negativo') then
    alter table public.materiais_mpdv add constraint mpdv_estoque_nao_negativo check (estoque >= 0) not valid;
  end if;
end $$;

