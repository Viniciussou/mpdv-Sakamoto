-- 9.1 Alterar andamento / aprovar / rejeitar / cancelar
create or replace function public.mpdv_atualizar_status(p_id uuid, p_status text, p_mensagem text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_sol public.solicitacoes_mpdv;
  v_msg text := left(nullif(trim(coalesce(p_mensagem, '')), ''), 500);
begin
  perform public.mpdv_exigir_marketing();
  if p_status not in ('aguardando_analise','aprovado','em_separacao','em_transporte','entregue','cancelado','rejeitado') then
    raise exception 'Status inválido.' using errcode = 'P0001', detail = 'STATUS_INVALIDO';
  end if;

  select * into v_sol from public.solicitacoes_mpdv where id = p_id for update;
  if not found then
    raise exception 'Solicitação não encontrada.' using errcode = 'P0001', detail = 'NAO_ENCONTRADA';
  end if;
  if v_sol.status = p_status then
    raise exception 'A solicitação já está neste status.' using errcode = 'P0001', detail = 'TRANSICAO_INVALIDA';
  end if;
  if not public.mpdv_transicao_permitida(v_sol.status, p_status) then
    raise exception 'Não é possível mudar de "%" para "%".', v_sol.status, p_status using errcode = 'P0001', detail = 'TRANSICAO_INVALIDA';
  end if;

  if p_status in ('cancelado','rejeitado') then
    perform public.mpdv_devolver_estoque(v_sol.id);
  end if;

  update public.solicitacoes_mpdv set
      status = p_status,
      atualizado_em = now(),
      cancelamento_liberado = case when p_status in ('cancelado','rejeitado','entregue','em_transporte') then false else cancelamento_liberado end,
      cancelado_em        = case when p_status = 'cancelado' then now() else cancelado_em end,
      cancelado_por       = case when p_status = 'cancelado' then v_uid else cancelado_por end,
      cancelado_por_papel = case when p_status = 'cancelado' then 'marketing' else cancelado_por_papel end,
      motivo_cancelamento = case when p_status = 'cancelado' then v_msg else motivo_cancelamento end
    where id = v_sol.id;

  insert into public.solicitacao_historico_mpdv (solicitacao_id, evento, status_anterior, status_novo, mensagem, usuario_id, usuario_papel)
  values (v_sol.id, case when p_status = 'cancelado' then 'cancelamento' else 'status' end,
          v_sol.status, p_status, v_msg, v_uid, 'marketing');

  return jsonb_build_object('id', v_sol.id, 'status', p_status);
end $$;

-- 9.2 Autorizar/revogar o cancelamento pelo vendedor (útil em "em separação")
create or replace function public.mpdv_liberar_cancelamento(p_id uuid, p_liberar boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); v_sol public.solicitacoes_mpdv;
begin
  perform public.mpdv_exigir_marketing();
  select * into v_sol from public.solicitacoes_mpdv where id = p_id for update;
  if not found then
    raise exception 'Solicitação não encontrada.' using errcode = 'P0001', detail = 'NAO_ENCONTRADA';
  end if;
  if v_sol.status not in ('aguardando_analise','aprovado','em_separacao') then
    raise exception 'Neste status o vendedor não pode cancelar.' using errcode = 'P0001', detail = 'TRANSICAO_INVALIDA';
  end if;
  update public.solicitacoes_mpdv set cancelamento_liberado = p_liberar, atualizado_em = now() where id = v_sol.id;
  insert into public.solicitacao_historico_mpdv (solicitacao_id, evento, status_anterior, status_novo, mensagem, usuario_id, usuario_papel)
  values (v_sol.id, case when p_liberar then 'cancelamento_liberado' else 'cancelamento_revogado' end, v_sol.status, v_sol.status,
          case when p_liberar then 'O Marketing autorizou o cancelamento desta solicitação.' else 'A autorização de cancelamento foi retirada.' end,
          v_uid, 'marketing');
  return jsonb_build_object('id', v_sol.id, 'cancelamento_liberado', p_liberar);
end $$;

